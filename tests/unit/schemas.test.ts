test('boundary objects strip unknown fields; invalid costs and ids fail', () => {
  expect(S.RetryRequestSchema.parse({ requestId: 'a1234567-1234-4234-8234-123456789012', confirmCostCu: 200, secret: 'discard' })).toEqual({ requestId: 'a1234567-1234-4234-8234-123456789012', confirmCostCu: 200 });
  expect(S.RetryRequestSchema.safeParse({ requestId: 'bad', confirmCostCu: -1 }).success).toBe(false);
});
