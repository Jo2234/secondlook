export function pollSlots(taskMs: number): number[] {
  const slots: number[] = [];
  for (let t = POLL_FAST_MS; t < taskMs; t += t < POLL_FAST_UNTIL_MS ? POLL_FAST_MS : POLL_SLOW_MS) slots.push(t);
  return slots;
}
export const maxTaskGets = (taskMs: number): number => pollSlots(taskMs).length + MAX_GET_RETRIES + MAX_RESULT_REFRESHES;
